import { generateFilesOnly } from 'fumadocs-openapi';
import { createOpenAPI } from 'fumadocs-openapi/server';
import { mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { openapiDocuments } from '../lib/openapi';

const reference = path.resolve(
	path.dirname(fileURLToPath(import.meta.url)),
	'../content/reference'
);
const dashboard = path.join(reference, 'dashboard');

function formatMetaJson(content: Record<string, unknown>) {
	let json = JSON.stringify(content, null, '\t');
	const pages = content.pages;
	if (Array.isArray(pages) && pages.every((page) => typeof page === 'string')) {
		const inlineArray = `[${pages.map((page) => JSON.stringify(page)).join(', ')}]`;
		const inlinePages = `"pages": ${inlineArray}`;
		if (`\t${inlinePages}`.length <= 100) {
			json = json.replace(/\t"pages": \[\n(?:\t\t"[^"]+",?\n)+\t\]/, `\t${inlinePages}`);
		}
	}
	return `${json}\n`;
}

/**
 * Removes Fumadocs' generated notice and keeps one name for the page component. The description
 * loses its code marks, because the page header, the links to the next page, search and link
 * previews all show it as plain text.
 */
function formatPage(content: string) {
	if (!content.includes('full: true')) content = content.replace('---', '---\nfull: true');
	return content
		.replace(/^description:.*\n(?:[ \t].*\n)*/m, (description) => description.replaceAll('`', ''))
		.replace(
			/{\/\* This file was generated by Fumadocs\. Do not edit this file directly\. Any changes should be made by running the generation command again\. \*\/}/g,
			''
		)
		.replace(
			/ {2}const \{ APIPage, OpenAPIPage \} = props\.components \?\? \{\};\n {2}\/\/ "APIPage"[^\n]*\n {2}const Comp = OpenAPIPage \?\? APIPage;/,
			'  const { OpenAPIPage } = props.components ?? {};'
		)
		.replace('<Comp ', '<OpenAPIPage ')
		.replace(
			/<OpenAPIPage document="([^"]+)" operations=\{\[\{"path":"([^"]+)","method":"([^"]+)"\}\]\} \/>/g,
			"<OpenAPIPage document=\"$1\" operations={[{ path: '$2', method: '$3' }]} />"
		)
		.replace(/\n{3,}/g, '\n\n')
		.trimEnd()
		.concat('\n');
}

/** The folders of generated pages, one per tag. The pages beside them are written by hand. */
async function tagFolders(directory: string, keep?: string) {
	return (await readdir(directory, { withFileTypes: true }))
		.filter((entry) => entry.isDirectory() && entry.name !== keep)
		.map((entry) => path.join(directory, entry.name));
}

/**
 * Writes the pages that changed and deletes the pages of deleted operations. Unchanged pages stay
 * as they are, so a check that reads the reference while this runs never finds a page missing.
 */
async function writeReference(files: Map<string, string>) {
	for (const folder of [
		...(await tagFolders(reference, 'dashboard')),
		...(await tagFolders(dashboard))
	]) {
		for (const entry of await readdir(folder, { withFileTypes: true })) {
			const file = path.join(folder, entry.name);
			if (!files.has(file)) await rm(file, { recursive: true });
		}
		if ((await readdir(folder)).length === 0) await rm(folder, { recursive: true });
	}
	for (const [file, content] of files) {
		if ((await readFile(file, 'utf8').catch(() => undefined)) === content) continue;
		await mkdir(path.dirname(file), { recursive: true });
		await writeFile(file, content);
	}
}

async function main() {
	const referencePages = await generateFilesOnly({
		input: createOpenAPI({ input: { stogas: openapiDocuments.stogas } }),
		output: reference,
		per: 'operation',
		groupBy: 'tag',
		meta: {
			folderStyle: 'separator'
		},
		beforeWrite: (files) => {
			for (const file of files) {
				if (file.path.endsWith('meta.json')) {
					let content = JSON.parse(file.content);
					if (file.path === 'meta.json') {
						content = {
							title: 'API Reference',
							root: true,
							pages: [
								'index',
								'---Catalog---',
								'...catalog',
								'---Models---',
								'...openai-compatible',
								'...anthropic-compatible',
								'---Policies---',
								'...policies',
								'---Credentials---',
								'...credentials',
								'---API behavior---',
								'provider-behavior',
								'errors',
								'filters',
								'security',
								'---Dashboard API---',
								'...dashboard',
								'...'
							]
						};
					}
					content.pages = content.pages?.map((page: string) =>
						page === '---Open A I compatible---' ? '---Models---' : page
					);
					if (content.title === 'Open A I compatible') {
						content.title = 'Models';
						content.description = 'Model inference endpoints.';
					}
					if (file.path === path.join('openai-compatible', 'meta.json')) {
						content.title = 'Models';
						content.description = 'Model inference endpoints.';
					}
					if (file.path === path.join('anthropic-compatible', 'meta.json')) {
						content.title = 'Anthropic-compatible';
						content.description = "Anthropic's Messages API.";
					}
					if (file.path === path.join('policies', 'meta.json')) {
						content.title = 'Policies';
						content.description = 'Policy check endpoint.';
					}
					if (file.path === path.join('credentials', 'meta.json')) {
						content.title = 'Credentials';
						content.description = 'Provider credential checks.';
					}
					if (file.path === path.join('catalog', 'meta.json')) {
						content.title = 'Catalog';
						content.description = 'Public model and routing discovery endpoints.';
					}
					file.content = formatMetaJson(content);
				}
				if (file.path.endsWith('.mdx')) {
					file.content = formatPage(file.content);
					if (
						file.content.includes("path: '/v1/responses'") ||
						file.content.includes("path: '/v1/chat/completions'") ||
						file.content.includes("path: '/v1/messages'")
					) {
						file.content = file.content
							.replace(
								'  const { OpenAPIPage } = props.components ?? {};',
								'  const { Callout, OpenAPIPage } = props.components ?? {};'
							)
							.replace(
								'<OpenAPIPage ',
								`<Callout type="info" title="Verified connections">
        Send this request through a <a href="/docs/sdk-overview">Stogas SDK</a> to verify the gateway
        and encrypt the request. The request and response formats stay the same. See <a href="/docs/connection-modes">Connection modes</a> and <a href="/docs/reference/provider-behavior">Compatibility notes</a>.
      </Callout>

      <OpenAPIPage `
							);
					}
				}
			}
		}
	});
	const dashboardPages = await generateFilesOnly({
		input: createOpenAPI({ input: { dashboard: openapiDocuments.dashboard } }),
		output: dashboard,
		per: 'operation',
		groupBy: 'tag',
		meta: true,
		beforeWrite(files) {
			// Fumadocs spaces out capitals in tag names, as in "A P I keys".
			const tags = new Map(
				(this.generatedEntries.dashboard ?? []).flatMap((entry) =>
					entry.type === 'group' && entry.tag ? [[entry.path, entry.tag.name]] : []
				)
			);
			for (const file of files) {
				if (file.path === 'meta.json') {
					// The hand-written overview comes first, then the tags in alphabetical order.
					const { pages } = JSON.parse(file.content) as { pages: string[] };
					file.content = formatMetaJson({ pages: ['index', ...pages.sort()] });
				} else if (file.path.endsWith('meta.json')) {
					// Tag folders stay closed until one holds the open page, so the sidebar lists the tags.
					const meta = JSON.parse(file.content);
					file.content = formatMetaJson({
						...meta,
						title: tags.get(path.dirname(file.path)),
						defaultOpen: false
					});
				} else file.content = formatPage(file.content);
			}
		}
	});
	await writeReference(
		new Map([
			...referencePages.map((file) => [path.join(reference, file.path), file.content] as const),
			...dashboardPages.map((file) => [path.join(dashboard, file.path), file.content] as const)
		])
	);
	console.log('API documentation generated.');
}

await main();
